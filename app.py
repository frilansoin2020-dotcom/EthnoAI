@app.route("/")
def home():
    return render_template("index.html")


@app.route("/ask", methods=["POST"])
def ask():

    data = request.get_json()
    question = data.get("question", "").strip().lower()

    print(">>> ВОПРОС:", question, flush=True)

    if not question:
        return jsonify({
            "answer": "Пожалуйста, задайте вопрос."
        })

    # Убираем знаки препинания
    normalized_question = re.sub(
        r"[^\w\sёәғқңөұүіһ]",
        " ",
        question
    )

    normalized_question = re.sub(
        r"\s+",
        " ",
        normalized_question
    ).strip()
    normalized_question = normalized_question.replace("ё", "е")

    # =================================================
    # 1. ИЩЕМ НАЗВАНИЕ ТРАДИЦИИ В ВОПРОСЕ
    # =================================================

    for key, item in knowledge_base.items():

        title = item["title"].lower()

        if title in normalized_question:

            print(
                ">>> НАЗВАНИЕ НАЙДЕНО:",
                key,
                "|",
                title,
                flush=True
            )

            answer = (
                f"<b>{item['title']}</b><br><br>"
                f"{item['text']}<br><br>"
                f"<i>Название традиции найдено в вопросе.</i>"
            )

            return jsonify({
                "answer": answer
            })

    # =================================================
    # 2. УТОЧНЯЕМ ПО КОНТЕКСТУ
    # =================================================

    # Если речь идёт именно о семейном торжестве,
    # выбираем Бесік тойы, а не Бесікке салу.

    if (
        "торжество" in normalized_question
        or "праздник" in normalized_question
    ) and "бесік" in normalized_question:

        item = knowledge_base["бесік тойы"]

        print(
            ">>> КОНТЕКСТ УТОЧНЕН: бесік тойы",
            flush=True
        )

        answer = (
            f"<b>{item['title']}</b><br><br>"
            f"{item['text']}<br><br>"
            f"<i>Определено с учётом контекста вопроса.</i>"
        )

        return jsonify({
            "answer": answer
        })
    # =================================================
    # 2. ИЩЕМ СМЫСЛОВУЮ ФРАЗУ
    # =================================================

    best_key = None
    best_phrase = ""
    best_length = 0

    for key, phrases in context_rules.items():

        for phrase in phrases:

            phrase_lower = phrase.lower()

            if phrase_lower in normalized_question:

                if len(phrase_lower) > best_length:

                    best_key = key
                    best_phrase = phrase
                    best_length = len(phrase_lower)


    if best_key:

        item = knowledge_base[best_key]

        print(
            ">>> КОНТЕКСТ НАЙДЕН:",
            best_key,
            "|",
            best_phrase,
            flush=True
        )

        answer = (
            f"<b>{item['title']}</b><br><br>"
            f"{item['text']}<br><br>"
            f"<i>Определено по смысловой фразе: "
            f"«{best_phrase}».</i>"
        )

        return jsonify({
            "answer": answer
        })


    # =================================================
    # 3. ИЩЕМ ЦЕЛУЮ КЛЮЧЕВУЮ ФРАЗУ
    # =================================================

    for key, item in knowledge_base.items():

        for keyword in item["keywords"]:

            keyword_lower = keyword.lower()

            if keyword_lower in normalized_question:

                print(
                    ">>> КЛЮЧЕВАЯ ФРАЗА НАЙДЕНА:",
                    key,
                    "|",
                    keyword,
                    flush=True
                )

                answer = (
                    f"<b>{item['title']}</b><br><br>"
                    f"{item['text']}<br><br>"
                    f"<i>Определено по ключевой фразе: "
                    f"«{keyword}».</i>"
                )

                return jsonify({
                    "answer": answer
                })


    # =================================================
    # 4. ОТВЕТ НЕ НАЙДЕН
    # =================================================

    print(
        ">>> ОТВЕТ НЕ НАЙДЕН",
        flush=True
    )

    return jsonify({
        "answer": (
            "Я пока не знаю ответа на этот вопрос.<br><br>"
            "Попробуйте спросить о казахских традициях, "
            "обрядах, праздниках, домбре, қымыз или киіз үй."
        )
    })


if __name__ == "__main__":
    app.run(debug=True)