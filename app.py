def prepare_image(image_bytes):
    image = Image.open(io.BytesIO(image_bytes))

    # Уменьшаем изображение, если оно слишком большое
    image.thumbnail((1200, 1200))

    # Переводим в обычный цветовой формат
    if image.mode != "RGB":
        image = image.convert("RGB")

    # Сохраняем в JPEG с хорошим качеством
    output = io.BytesIO()
    image.save(output, format="JPEG", quality=85, optimize=True)

    return output.getvalue(), "image/jpeg"
@app.route("/search_images", methods=["POST"])
def search_images():
    data = request.get_json()
    query = data.get("query", "").strip()

    if not query:
        return jsonify({"images": [], "error": "Введите название для поиска."})

    search_url = (
        "https://commons.wikimedia.org/w/api.php?"
        + urllib.parse.urlencode({
            "action": "query",
            "format": "json",
            "generator": "search",
            "gsrsearch": query + " filetype:bitmap",
            "gsrnamespace": 6,
            "gsrlimit": 12,
            "prop": "imageinfo",
            "iiprop": "url",
            "iiurlwidth": 400
        })
    )

    try:
        req = urllib.request.Request(
            search_url,
            headers={"User-Agent": "EthnoAI/1.0 (educational project)"}
        )

        with urllib.request.urlopen(
            req,
            timeout=15,
            context=ssl.create_default_context(cafile=certifi.where())
        ) as response:
            result = json.loads(response.read().decode("utf-8"))

        pages = result.get("query", {}).get("pages", {})
        images = []

        for page in pages.values():
            info = page.get("imageinfo", [{}])[0]

            images.append({
                "title": page.get("title", "").replace("File:", ""),
                "url": info.get("thumburl", info.get("url", "")),
                "original_url": info.get("url", "")
            })

        return jsonify({"images": images})

    except urllib.error.HTTPError as error:
        print("Ошибка поиска изображений:", error)

        if error.code == 429:
            message = "Сервис временно ограничил поиск изображений. Попробуйте немного позже."
        else:
            message = "Не удалось выполнить поиск. Попробуйте ещё раз."

        return jsonify({
            "images": [],
            "error": message
        })

    except Exception as error:
        print("Ошибка поиска изображений:", error)
        return jsonify({
            "images": [],
            "error": "Не удалось выполнить поиск. Попробуйте ещё раз."
        })


